export const copy = new Proxy({} as typeof english, {
  get(_target, key: string) {
    const p = preferences();
    if (key === "cheapGames") {
      const amount = new Intl.NumberFormat(locale(), {
        style: "currency",
        currency: p.currency,
        maximumFractionDigits: 0,
      }).format(10);
      return p.language === "ru"
        ? `Игры до ${amount}`
        : p.language === "lt"
          ? `Žaidimai iki ${amount}`
          : `Games under ${amount}`;
    }
    if (p.language === "lt") return lithuanian[key as keyof typeof lithuanian];
    return p.language === "ru"
      ? (russian[key as keyof typeof russian] ??
          english[key as keyof typeof english])
      : english[key as keyof typeof english];
  },
});
export function valueLabel(value: string) {
  const labels: Record<string, string> = {
    Global: "Весь мир",
    Europe: "Европа",
    "North America": "Северная Америка",
    Action: "Экшен",
    Adventure: "Приключения",
    RPG: "Ролевая игра",
    Strategy: "Стратегия",
    Simulation: "Симулятор",
    Racing: "Гонки",
  };
  const lt: Record<string, string> = {
    Global: "Visas pasaulis",
    Europe: "Europa",
    "North America": "Šiaurės Amerika",
    Action: "Veiksmo",
    Adventure: "Nuotykių",
    RPG: "Vaidmenų",
    Strategy: "Strategijos",
    Simulation: "Simuliatoriai",
    Racing: "Lenktynių",
  };
  const language = preferences().language;
  return language === "ru"
    ? (labels[value] ?? value)
    : language === "lt"
      ? (lt[value] ?? value)
      : value;
}
